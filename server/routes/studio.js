// POST /api/v1/studio/apply
router.post('/studio/apply', authenticateOnly, async (req, res) => {
  try {
    const user = req.user;
    const { profileId, changes } = req.body;
    if (!changes) return res.status(400).json({ error: 'changes required' });

    let profile = profileId
      ? await UserAiConfig.findOne({ _id: profileId, userId: user._id })
      : await UserAiConfig.findOne({ userId: user._id });
    if (!profile) return res.status(404).json({ error: 'Профиль не найден' });

    if (changes.systemPrompt   != null) profile.systemPrompt                   = changes.systemPrompt;
    if (changes.restrictions   != null) profile.restrictions                   = changes.restrictions;
    if (changes.triggerMode    != null) profile.botSettings.triggerMode        = changes.triggerMode;
    if (changes.triggerKeyword != null) profile.botSettings.triggerKeyword     = changes.triggerKeyword;
    if (changes.historyMode    != null) profile.botSettings.historyMode        = changes.historyMode;
    if (changes.aiAccessRole   != null) profile.botSettings.aiAccessRole       = changes.aiAccessRole;
    if (changes.welcomeMessage != null) profile.botSettings.welcomeMessage     = changes.welcomeMessage;
    // Вертикализуем раскладку кнопок (1 кнопка = 1 ряд) — иначе на мобилке ряды
    // из 2+ кнопок обрезаются. Тот же нормализатор, что и в AI-пайплайне.
    if (changes.commands       != null) profile.botSettings.commands           = require('../helpers/keyboardLayout').stackCommands(changes.commands);
    if (changes.aiName         != null) profile.aiName                         = changes.aiName;

    await profile.save();

    try {
      const UserIntegrations = require('../models/UserIntegrations');
      const integrationsDoc = await UserIntegrations.findOne({ userId: user._id }).lean();
      const tgInstances = (integrationsDoc?.telegram || []).filter(
        (inst) => inst.connected && String(inst.profileId) === String(profile._id)
      );
      const slashCommands = (profile.botSettings?.commands || [])
        .filter(c => c.command?.startsWith('/') && c.command.length > 1)
        .map(c => ({ command: c.command.replace(/^\//, '').toLowerCase(), description: c.description || c.command }));
      for (const inst of tgInstances) {
        if (!inst.token) continue;
        await fetch(`https://api.telegram.org/bot${inst.token}/setMyCommands`, {
          method: 'POST', headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ commands: slashCommands }),
        }).catch(() => {});
      }
    } catch {}

    res.json({ success: true });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// POST /api/v1/studio/chat
router.post('/studio/chat', authenticateOnly, async (req, res) => {
  try {
    const user = req.user;
    const { profileId, message, currentConfig, image, currentScreen } = req.body;
    if (!message) return res.status(400).json({ error: 'message required' });
    const hasImage = typeof image === 'string' && image.startsWith('data:image/');

    const studioProfile = await getOrCreateStudioProfile(user);

    let dataContext = '';
    try {
      const UserSchema = require('../models/UserSchema');
      const UserRecord = require('../models/UserRecord');
      const schemas = await UserSchema.find({ userId: user._id }).select('name label description fields').lean();
      if (schemas.length > 0) {
        dataContext = '\n\n[ДАННЫЕ ПОЛЬЗОВАТЕЛЯ]\nСхемы данных, доступные для DB_COMMAND:';
        for (const schema of schemas) {
          const records = await UserRecord.find({ userId: user._id, schemaId: schema._id }).select('data _id').limit(10).lean();
          dataContext += `\n\nСхема: "${schema.label || schema.name}" (name для DB_COMMAND: "${schema.name}")`;
          if (schema.description) dataContext += ` — ${schema.description}`;
          dataContext += `\nПоля: ${(schema.fields || []).map(f => `${f.name} (${f.label || f.name}, тип: ${f.type || 'text'})`).join(', ')}\n`;
          if (records.length > 0) {
            dataContext += `Записи (${records.length}):\n`;
            records.forEach(r => { dataContext += `  _id:${r._id} ${JSON.stringify(r.data)}\n`; });
          } else { dataContext += `Записей пока нет.\n`; }
        }
      }
    } catch {}

    // Fetched fresh from DB rather than trusting the client-sent currentConfig
    // (older client builds don't know about this field) — model's own running
    // memory of decisions/gaps for this specific bot, see <BUILD_NOTES>.
    let buildNotesSection = '';
    if (profileId) {
      const targetProfile = await UserAiConfig.findById(profileId).select('studioBuildNotes').lean().catch(() => null);
      if (targetProfile?.studioBuildNotes) {
        buildNotesSection = `\n\n[ЗАМЕТКИ РАЗРАБОТЧИКА]\n${targetProfile.studioBuildNotes}`;
      }
    }

    const configJson = JSON.stringify(currentConfig || {}, null, 2);
    // Экран, на котором сейчас стоит предпросмотр у пользователя. Если он просит
    // «поменяй текст на …» / «хочу такой текст: …» и НЕ называет экран — правим
    // именно этот (см. STUDIO_SYSTEM_PROMPT, раздел про SCREEN_TEXT).
    let screenSection = '';
    if (typeof currentScreen === 'string' && currentScreen.trim()) {
      const scr = currentScreen.trim();
      const scrLabel = scr === '/start' ? 'Главное меню (/start)' : scr;
      screenSection = `\n\n[ТЕКУЩИЙ ЭКРАН ПРЕДПРОСМОТРА]\n${scrLabel}\n(Если пользователь просит изменить текст и НЕ указал явно другой экран/вкладку — правь именно ЭТОТ экран через <SCREEN_TEXT screen="${scr}">…</SCREEN_TEXT>.)`;
    }
    const fullPrompt = `[ТЕКУЩИЙ КОНФИГ]\n${configJson}${dataContext}${buildNotesSection}${screenSection}\n\n[ЗАПРОС]\n${message}`;

    const task = new Task({
      taskId: uuidv4(), userId: user._id, prompt: fullPrompt, rawPrompt: message,
      context: { source: 'studio', targetProfileId: profileId || null },
      profileId: studioProfile._id, status: 'pending',
      endUser: { platform: 'studio', platformUserId: user._id.toString() },
    });
    await task.save();
    if (hasImage) aiService.pendingImages.set(task.taskId, image);

    res.status(202).json({ success: true, taskId: task.taskId });
  } catch (err) {
    console.error('❌ /studio/chat error:', err.message, err.stack?.split('\n')[1]);
    res.status(500).json({ error: err.message });
  }
});

