// Find-or-create the per-user "__studio__" scratch profile — the AI's own persona
// for reasoning about bot design (distinct from the bot-under-construction's profile).
// Shared by the website's /studio/chat and TGLetBot's Telegram-driven builder flow.
async function getOrCreateStudioProfile(user) {
  const studioChatId = process.env.STUDIO_CHAT_ID_MISTRAL;
  const studioQwenChatId = process.env.STUDIO_CHAT_ID_QWEN;
  const allStudio = await UserAiConfig.find({ userId: user._id, profileName: '__studio__' })
    .sort({ createdAt: 1 }).lean();
  if (allStudio.length > 1) {
    await UserAiConfig.deleteMany({
      userId: user._id, profileName: '__studio__',
      _id: { $nin: [allStudio[0]._id] },
    });
  }
  let studioProfile = allStudio.length > 0 ? await UserAiConfig.findById(allStudio[0]._id) : null;

  if (!studioProfile) {
    studioProfile = new UserAiConfig({
      userId: user._id, profileName: '__studio__', aiName: 'Bot Studio',
      systemPrompt: STUDIO_SYSTEM_PROMPT,
      mistralChatId: studioChatId || null,
      qwenStudioThreadId: studioQwenChatId || null,
      hasPersonalThread: !!(studioChatId || studioQwenChatId),
    });
    await studioProfile.save();
  } else {
    let changed = false;
    if (studioProfile.systemPrompt !== STUDIO_SYSTEM_PROMPT) { studioProfile.systemPrompt = STUDIO_SYSTEM_PROMPT; changed = true; }
    if (studioChatId && studioProfile.mistralChatId !== studioChatId) { studioProfile.mistralChatId = studioChatId; changed = true; }
    if (studioQwenChatId && studioProfile.qwenStudioThreadId !== studioQwenChatId) { studioProfile.qwenStudioThreadId = studioQwenChatId; changed = true; }
    if (changed) await studioProfile.save();
  }
  return studioProfile;
}

