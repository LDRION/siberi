async function main() {
  await mongoose.connect(process.env.MONGO_URI);
  console.log('✓ MongoDB подключена');

  const admin = await User.findOne({ email: ADMIN_EMAIL });
  if (!admin) {
    console.error(`✗ Пользователь ${ADMIN_EMAIL} не найден`);
    process.exit(1);
  }
  console.log(`✓ Аккаунт найден: ${admin.email} (${admin._id})`);

  let created = 0;
  let updated = 0;

  for (const bot of BOTS) {
    const existing = await UserAiConfig.findOne({ userId: admin._id, profileName: bot.profileName });

    const doc = {
      userId: admin._id,
      profileName: bot.profileName,
      aiName: bot.aiName,
      color: bot.color,
      systemPrompt: bot.systemPrompt,
      restrictions: bot.restrictions || '',
      mistralChatId: null,
      hasPersonalThread: false,
      isDefault: false,
      updatedAt: new Date(),
      botSettings: {
        triggerMode: 'respond_all',
        triggerKeyword: '',
        historyMode: 'personal',
        welcomeMessage: bot.welcomeMessage,
        commands: bot.commands,
      },
    };

    if (existing) {
      await UserAiConfig.updateOne({ _id: existing._id }, { $set: doc });
      console.log(`  ↺ Обновлён: ${bot.profileName}`);
      updated++;
    } else {
      await UserAiConfig.create(doc);
      console.log(`  ✓ Создан: ${bot.profileName}`);
      created++;
    }
  }

  console.log(`\n✅ Готово: создано ${created}, обновлено ${updated} ботов`);
  process.exit(0);
}

main().catch(e => { console.error('✗ Ошибка:', e.message); process.exit(1); });
