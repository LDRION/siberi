'use strict';

// Наблюдение за попытками собрать мошеннического бота в конструкторе.
//
// ВАЖНО — это МОНИТОРИНГ, а не блокировка: пользователь ничего не замечает и
// продолжает работать, админам просто прилетает сигнал «посмотрите». Решение
// (заблокировать / забить) принимает человек. Так и просил владелец: авто-блока
// нет, потому что ложное срабатывание не должно рубить живого клиента.
//
// Работает НЕЗАВИСИМО от отказа модели: даже если промпт студии не сработал и
// ИИ послушно собрала мошенника — сигнал всё равно уйдёт. Детект детерминированный,
// поэтому не зависит от настроения модели.
//
// ⚠️ ГРАБЛИ: в JS `\w` — это [A-Za-z0-9_], кириллицу он НЕ матчит. `притвор\w+`
// молча не ловит «притворись». Поэтому везде ниже — явный класс [а-яё], а не \w.
//
// Повод: @rocikm981 собирала бота, выдающего себя за Telegram, с угрозами и
// спрятанной суммой Stars («сделай как реального человека-мошенника»).

const ORG = '(?:telegram|телеграм|банк[а-яё]*|сбер[а-яё]*|тинькоф[а-яё]*|альфа|госуслуг[а-яё]*|поддержк[а-яё]*|техподдержк[а-яё]*|маркетплейс[а-яё]*|wildberries|ozon|озон|валберис)';

// СИЛЬНЫЕ маркеры — одного достаточно (вес 2). Формулировки, которые почти не
// встречаются в легальных задачах.
const STRONG = [
  { re: /подар(?:ок|ки|ка)\s+от\s+(?:telegram|телеграм)/i,                        tag: 'выдаёт себя за Telegram («подарок от Telegram»)' },
  { re: /служб[а-яё]*\s+безопасност[а-яё]*\s+(?:банк|сбер|тинькоф|альфа)/i,        tag: 'выдаёт себя за службу безопасности банка' },
  { re: /(?:как|будто)\s+(?:настоящ[а-яё]*\s+|реальн[а-яё]*\s+)?(?:человек[а-яё]*[-\s])?мошенник/i, tag: 'прямо просит «как мошенник»' },
  { re: /(?:код[а-яё]*\s+из\s+смс|смс[-\s]?код|одноразов[а-яё]*\s+код|2fa|двухфактор|cvv|cvc|seed[-\s]?фраз|сид[-\s]?фраз)/i, tag: 'выманивание кодов/секретов (СМС, 2FA, CVV, seed)' },
  { re: /не\s+(?:называ|упомина|пиш|говор|указыва|раскрыва)[а-яё]*\s+(?:про\s+)?(?:сумм|цен|стоимост|скольк|что\s+это\s+оплат|об\s+оплат|про\s+оплат)/i, tag: 'просит скрыть сумму/факт оплаты' },
  { re: /(?:скам[-\s]?бот|развод(?:ить|няк)\s+(?:людей|на\s+деньги)|фишингов[а-яё]*\s+бот)/i, tag: 'прямое указание на скам' },
];

// СЛАБЫЕ маркеры (вес 1) — по отдельности бывают в легальных ботах (жёсткий тон,
// акции), поэтому сигналим только при ДВУХ. Так «строгий коллектор» не ловится.
const WEAK = [
  { re: new RegExp(`(?:представ(?:ься|ляйся|иться)|притвор[а-яё]+|выдава[а-яё]+\\s+себя|прикинь[а-яё]*)\\s+(?:за\\s+)?${ORG}`, 'i'), tag: 'просит представляться чужой организацией' },
  { re: /(?:обещай|пообещай|скажи,?\s*что)\s+(?:[а-яёa-z]+\s+){0,3}?(?:приз|выигр|подар|компенсац|выплат|бонус)/i, tag: 'фальшивые призы/выплаты как приманка' },
  { re: /(?:угрожа|запугива|шантаж)[а-яё]*/i,                                      tag: 'угрозы пользователю' },
  { re: /аккаунт\s+(?:будет\s+)?(?:заблокир|удал)[а-яё]*|заблокиру[а-яё]*\s+аккаунт/i, tag: 'запугивание блокировкой аккаунта' },
  // «переве[дл]» не ловит «перевеСти» — основы разные, поэтому широкий [а-яё]*
  { re: /(?:переве[а-яё]*|перечисл[а-яё]+|отправ[а-яё]+|скинь[а-яё]*|закинь[а-яё]*)\s+(?:звёзд|звезд|stars|деньг|средств|рубл)/i, tag: 'требование перевести деньги/Stars' },
  // «пришл» не ловит «приСЛал» — нужны обе основы. Пароль и карта — РАЗНЫЕ
  // маркеры: «введите пароль для входа в админку» легален и даст лишь 1 балл,
  // а «пришли пароль и данные карты» наберёт 2 и просигналит.
  { re: /(?:введ[а-яё]+|присл[а-яё]+|пришл[а-яё]+|отправ[а-яё]+|скинь[а-яё]*|напиш[а-яё]+)\s+(?:мне\s+|свой\s+|своё\s+|свои\s+)?(?:парол|логин\s+и\s+парол)/i, tag: 'выманивание пароля' },
  { re: /(?:данн[а-яё]*\s+карт|номер\s+карт|реквизит[а-яё]*\s+карт|привяз[а-яё]+\s+карт)/i, tag: 'сбор данных банковской карты' },

  // ── Фейковая «раздача призов» (развод детей на игровые предметы) ──────────
  // По отдельности легальны (у магазина бывает колесо фортуны, фан-бот про
  // Roblox — норм). Скам — это СТЕК: азартная механика + игровой контекст +
  // «все выигрывают». Порог 2 отсекает одиночные легальные акции. Повод —
  // @StarPetsMM2Gifts_bot (23.07): «испытай удачу → крути → ты выиграл → выбери сет».
  { re: /испыта[а-яё]*\s+удач|прокрут[а-яё]+|крутан[а-яё]+|\bкрути\b|колес[а-яё]*\s+фортун|рулетк[а-яё]*|джекпот|барабан[а-яё]*\s+удач/i, tag: 'азартная механика (крути/испытай удачу/рулетка)' },
  { re: /\bmm2\b|murder\s*mystery|adopt\s*me|roblox|роблокс|робукс|robux|standoff|brawl|blox\s*fruit|блокс\s*фрут|игров[а-яё]+\s+(?:предмет|сет|скин|валют)/i, tag: 'игровые предметы (Roblox/MM2/пет/скин)' },
  { re: /(?:ты|вы|все|каждый)\s+выигра[а-яё]+|объявлени[а-яё]*\s+выигрыш|гарантирован[а-яё]*\s+(?:приз|выигрыш|подар)|100\s*%\s*выигр/i, tag: '«все выигрывают» / гарантированный выигрыш' },
  { re: /(?:бесплатн[а-яё]*|халяв[а-яё]*|даром)\s+(?:[а-яё]+\s+){0,2}?(?:приз|подар|сет|скин|робукс|robux|пет|выигр|прокрут|крут)/i, tag: 'бесплатный приз/скин как приманка' },
];

// Анти-ложняки: ЗАЩИТНЫЕ формулировки. Бот, который ПРЕДУПРЕЖДАЕТ о мошенниках
// или учит их распознавать — легален и тревогу поднимать не должен.
// Допускаем слова между глаголом и объектом («предупреждать КЛИЕНТОВ о мошенниках»)
// и разные основы («защищать» ≠ «защит», поэтому «защи[а-яё]*»).
const DEFENSIVE = /(?:защи[а-яё]*|предупрежд[а-яё]*|предостерег[а-яё]*|распозна[а-яё]*|выявл[а-яё]*|борьб[а-яё]*|бороться|антифрод)[^.!?]{0,40}(?:мошенник|скам|фишинг)|(?:мошенник|скам|фишинг)[а-яё]*[^.!?]{0,40}(?:защи[а-яё]*|предупрежд[а-яё]*|предостерег[а-яё]*|распозна[а-яё]*)/i;

// Разбирает текст запроса. null — чисто; иначе {score, markers}.
function detectFraudIntent(text) {
  const t = String(text || '');
  if (t.length < 8) return null;
  if (DEFENSIVE.test(t)) return null;

  const hits = [];
  for (const { re, tag } of STRONG) if (re.test(t)) hits.push({ tag, weight: 2 });
  for (const { re, tag } of WEAK) if (re.test(t)) hits.push({ tag, weight: 1 });
  const score = hits.reduce((s, h) => s + h.weight, 0);
  if (score < 2) return null; // один слабый маркер — не повод дёргать админов
  return { score, markers: hits.map((h) => h.tag) };
}

// Скан КОНФИГА уже собранного (живого) бота: системный промпт + приветствие +
// ответы команд склеиваем и прогоняем через detectFraudIntent. Нужно потому,
// что fraudWatch на запросе видит лишь ЧТО человек попросил при сборке, а скам
// живёт в получившемся системном промпте — его никто не проверял (дыра, из-за
// которой @StarPetsMM2Gifts_bot всплыл лишь когда технически падал).
function scanBotConfig(config) {
  if (!config) return null;
  const bs = config.botSettings || {};
  const parts = [config.systemPrompt || '', bs.welcomeMessage || ''];
  for (const c of (bs.commands || [])) if (c && c.response) parts.push(c.response);
  return detectFraudIntent(parts.join('\n'));
}

module.exports = { detectFraudIntent, scanBotConfig };
