// ── Markdown (LLM output) → Telegram-safe HTML ──────────────────────────────────
// Groq writes plain GFM markdown (**bold**, `* ` bullets) by default. Telegram's
// legacy parse_mode="Markdown" doesn't speak that dialect (single * = bold, no
// native lists) — mismatched syntax throws "can't parse entities" and the whole
// message falls back to raw unformatted text. HTML has far fewer footguns, so we
// convert instead of relying on Telegram to parse the model's own markdown.
function escapeHtml(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function linkifyBrandHtml(html) {
  const placeholders = [];
  let out = html.replace(/<a href="([^"]*)">([^<]*)<\/a>/g, (m, href, inner) => {
    const fixedHref = /^Siberi\.AI$/i.test(inner.trim()) ? SITE : href;
    placeholders.push(`<a href="${fixedHref}">${inner}</a>`);
    return ` ${placeholders.length - 1} `;
  });
  out = out.replace(/Siberi\.AI/gi, `<a href="${SITE}">Siberi.AI</a>`);
  out = out.replace(/ (\d+) /g, (_, i) => placeholders[Number(i)]);
  return out;
}

function mdToTelegramHtml(raw) {
  let t = escapeHtml(raw);
  t = t.replace(/```([\s\S]*?)```/g, (_, code) => `<pre>${code}</pre>`);
  t = t.replace(/`([^`]+)`/g, '<code>$1</code>');
  t = t.replace(/^[ \t]*#{1,6}[ \t]+(.*)$/gm, '<b>$1</b>');     // # Heading -> bold
  t = t.replace(/^[ \t]*[*-][ \t]+/gm, '▪️ ');                  // * / - bullets -> ▪️
  t = t.replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, '<a href="$2">$1</a>');
  t = t.replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>');
  t = t.replace(/__([^_]+)__/g, '<b>$1</b>');
  t = t.replace(/\*([^*\n]+)\*/g, '<i>$1</i>');
  t = t.replace(/(?<!\w)_([^_\n]+)_(?!\w)/g, '<i>$1</i>');
  return linkifyBrandHtml(t);
}

