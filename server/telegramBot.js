// Groq SDK's `timeout` only covers time-to-first-byte (cleared once fetch() resolves
// headers) — a stream that starts but then goes silent mid-way isn't caught by it.
// Races each chunk against a stall timer so a mid-stream hang fails over just as fast.
async function* withStallTimeout(stream, stallMs) {
  const iterator = stream[Symbol.asyncIterator]();
  while (true) {
    const result = await Promise.race([
      iterator.next(),
      new Promise((_, reject) => setTimeout(() => reject(new Error(`Groq stream stalled — no data for ${stallMs}ms`)), stallMs)),
    ]);
    if (result.done) return;
    yield result.value;
  }
}

