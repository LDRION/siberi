// ── Основной обработчик сообщений ─────────────────────────────────────────────
bot.on('text', async (ctx) => {
  const text = ctx.message.text;
  if (text.startsWith('/')) return;

  const session = getSession(ctx.from.id);

  // Распознаём «покажи демо для кофейни» и т.п. прямо из текста
  const intent = detectNicheIntent(text);
  if (intent) {
    session.demoNiche = intent.key;
    session.history = [];
    const niche = DEMO_NICHES[intent.key];
    const prefix = intent.related
      ? `Точного демо под ваш запрос пока нет, но вот максимально похожий живой пример:\n\n`
      : '';
    await ctx.replyWithHTML(prefix + niche.welcome, nicheHomeKb(intent.key));
    return;
  }

  const niche = session.demoNiche ? DEMO_NICHES[session.demoNiche] : null;

  try {
    const reply = await streamAI(
      ctx,
      session.history,
      text,
      niche ? niche.system : SYSTEM,
      niche ? nicheChatKb(session.demoNiche) : null
    );
    session.history.push({ role: 'user', content: text });
    session.history.push({ role: 'assistant', content: reply });
    if (session.history.length > 20) session.history = session.history.slice(-20);
  } catch (err) {
    console.error('Groq error:', err.message);
    await ctx.reply('Что-то пошло не так, попробуйте ещё раз.');
  }
});

