let groqDownSince = null;
let groqHealthInterval = null;

function isGroqDown(err) {
  const status = err?.status || err?.response?.status;
  const m = (err.message || '').toLowerCase();
  return (
    status === 429 || status === 500 || status === 502 || status === 503 || status === 529 ||
    m.includes('rate limit') || m.includes('quota') || m.includes('overloaded') ||
    m.includes('timeout') || m.includes('timed out') || m.includes('stalled') ||
    m.includes('econnreset') || m.includes('enotfound') || m.includes('network') ||
    m.includes('connection error')
  );
}

function onGroqDown() {
  if (groqDownSince) return;
  groqDownSince = Date.now();
  console.warn('🔴 Groq недоступен (бот) — фолбэк на каждое сообщение. Health-check каждые 5 мин.');
  if (groqHealthInterval) return;
  groqHealthInterval = setInterval(async () => {
    if (!groqDownSince) return;
    try {
      await groq.chat.completions.create({
        model: 'llama-3.3-70b-versatile',
        messages: [{ role: 'user', content: 'ping' }],
        max_tokens: 5,
      });
      groqDownSince = null;
      clearInterval(groqHealthInterval);
      groqHealthInterval = null;
      console.log('🟢 Groq вернулся (бот) — снова приоритет №1.');
    } catch {
      const mins = Math.round((Date.now() - groqDownSince) / 60000);
      console.log(`⏳ Groq недоступен уже ${mins} мин (бот), продолжаю с фолбэком.`);
    }
  }, 5 * 60 * 1000);
}

