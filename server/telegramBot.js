const sessions = new Map();

function getSession(userId) {
  if (!sessions.has(userId)) sessions.set(userId, { history: [], lastActivity: 0, demoNiche: null });
  const s = sessions.get(userId);
  s.lastActivity = Date.now();
  return s;
}

setInterval(() => {
  const cut = Date.now() - 3 * 60 * 60 * 1000;
  for (const [k, v] of sessions) if (v.lastActivity < cut) sessions.delete(k);
}, 20 * 60 * 1000);

// ── Анимация «Думаю...» ───────────────────────────────────────────────────────
const THINK_FRAMES = ['Думаю…', 'Думаю ▪', 'Думаю ▪▪', 'Думаю ▪▪▪'];

async function startThinking(ctx) {
  let msg;
  try { msg = await ctx.reply(THINK_FRAMES[0]); }
  catch { return { id: null, chat: null, stop: () => {} }; }
  let i = 0, active = true;
  const timer = setInterval(async () => {
    if (!active) return;
    i = (i + 1) % THINK_FRAMES.length;
    await ctx.telegram.editMessageText(ctx.chat.id, msg.message_id, undefined, THINK_FRAMES[i]).catch(() => {});
  }, 500);
  return {
    id:   msg.message_id,
    chat: ctx.chat.id,
    stop: () => { active = false; clearInterval(timer); },
  };
}

// ── Стриминг AI ───────────────────────────────────────────────────────────────
async function streamAI(ctx, history, text, systemPrompt = SYSTEM, extraKb = null) {
  const thinking = await startThinking(ctx);
  let fullText = '';
  let lastEditAt = 0;
  let animStopped = false;
  const EDIT_INTERVAL = 1400;

  if (groqDownSince) {
    // Уже знаем, что Groq лежит — не ждём заново 6с на проверку, сразу фолбэк
    animStopped = true;
    if (thinking.id) {
      await ctx.telegram.editMessageText(thinking.chat, thinking.id, undefined, 'Подбираю ответ, секунду…').catch(() => {});
    }
    fullText = await tryServerFallback(systemPrompt, text);
  } else {
    try {
      const stream = await groq.chat.completions.create({
        model:       'llama-3.3-70b-versatile',
        messages:    [{ role: 'system', content: systemPrompt }, ...history.slice(-14), { role: 'user', content: text }],
        max_tokens:  1024,
        temperature: 0.6,
        stream:      true,
      });

      for await (const chunk of withStallTimeout(stream, 10000)) {
        fullText += chunk.choices[0]?.delta?.content || '';
        const now = Date.now();
        if (thinking.id && fullText.length > 20 && now - lastEditAt > EDIT_INTERVAL) {
          if (!animStopped) { thinking.stop(); animStopped = true; }
          lastEditAt = now;
          await ctx.telegram.editMessageText(
            thinking.chat, thinking.id, undefined,
            mdToTelegramHtml(fullText) + ' ▌',
            { parse_mode: 'HTML', disable_web_page_preview: true }
          ).catch(() => {});
        }
      }
    } catch (err) {
      thinking.stop();
      animStopped = true;
      console.warn('⚠️ Groq упал, пробуем фолбэк через Mistral/Qwen:', err.message);
      if (isGroqDown(err)) onGroqDown();
      if (thinking.id) {
        await ctx.telegram.editMessageText(thinking.chat, thinking.id, undefined, 'Подбираю ответ, секунду…').catch(() => {});
      }
      fullText = await tryServerFallback(systemPrompt, text); // бросит, если и фолбэк не сработал
    }
  }

  if (!animStopped) thinking.stop();

  const finalText = fullText.trim();
  const kbOpts = extraKb || {};

  // Финальное сообщение — HTML, иначе plain без форматирования (на крайний случай)
  const sendFinal = async (html) => {
    const opts = { parse_mode: 'HTML', disable_web_page_preview: true, ...kbOpts };
    if (thinking.id) {
      try {
        await ctx.telegram.editMessageText(thinking.chat, thinking.id, undefined, html, opts);
      } catch {
        await ctx.telegram.editMessageText(thinking.chat, thinking.id, undefined, finalText, kbOpts).catch(async () => ctx.reply(finalText, kbOpts));
      }
    } else {
      try { await ctx.reply(html, opts); }
      catch { await ctx.reply(finalText, kbOpts); }
    }
  };

  await sendFinal(mdToTelegramHtml(finalText));
  return finalText;
}

