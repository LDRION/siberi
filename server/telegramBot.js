function detectNicheIntent(text) {
  if (!/покаж|демо|пример|посмотр|глянуть|хочу.{0,15}(увидеть|посмотреть)/i.test(text)) return null;
  for (const n of NICHE_INTENT) if (n.direct.test(text)) return { key: n.key, related: false };
  for (const n of NICHE_INTENT) if (n.related.test(text)) return { key: n.key, related: true };
  return null;
}

