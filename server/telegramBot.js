async function tryServerFallback(systemPrompt, text) {
  const res = await fetch(INTERNAL_API, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'x-internal-secret': INTERNAL_SECRET },
    body: JSON.stringify({ message: text, systemPrompt }),
    signal: AbortSignal.timeout(60000),
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok || !data.success) throw new Error(data.error || `fallback failed (${res.status})`);
  return data.result;
}
