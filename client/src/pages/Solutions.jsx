export default function Solutions({ apiKey }) {
  const [selected, setSelected] = useState('business');
  const navigate = useNavigate();

  const currentIndex = personas.findIndex((p) => p.id === selected);
  const activePersona = personas[currentIndex];

  const handleNext = () => {
    const nextIndex = (currentIndex + 1) % personas.length;
    setSelected(personas[nextIndex].id);
  };

  return (
    <div className="solutions-page">
      {/* Заголовок страницы даёт шапка оболочки (HEAD в Layout) — здесь его дублировать не нужно */}

      {/* Desktop: grid of all persona cards */}
      <div className="roles">
        {personas.map((p) => (
          <button
            key={p.id}
            type="button"
            className={`role${selected === p.id ? ' role--on' : ''}`}
            onClick={() => setSelected(p.id)}
          >
            <span className="role__ic">
              <p.icon size={20} />
            </span>
            <span className="role__n">{p.title}</span>
            <span className="role__t">{p.shortDesc}</span>
          </button>
        ))}
      </div>

      {/* Mobile: sticky single-card switcher */}
      {activePersona && (
        <div className="sol-mobile-switcher">
          <button className="sol-mobile-card" onClick={handleNext}>
            <div className="sol-mobile-card__icon">
              <activePersona.icon size={26} />
            </div>
            <div className="sol-mobile-card__text">
              <h3>{activePersona.title}</h3>
              <p>{activePersona.shortDesc}</p>
            </div>
            <ChevronRight size={20} className="sol-mobile-card__arrow" />
          </button>
          <div className="sol-mobile-dots">
            {personas.map((p, i) => (
              <button
                key={p.id}
                className={`sol-dot${i === currentIndex ? ' active' : ''}`}
                onClick={() => setSelected(p.id)}
                aria-label={p.title}
              />
            ))}
          </div>
        </div>
      )}

      {activePersona && (
        <div className="rolepanel card fade-in" key={selected}>
          <div className="rolepanel__h">
            <span className="rolepanel__ic">
              <activePersona.icon size={22} />
            </span>
            <h2>{activePersona.title}</h2>
          </div>

          <div className="rolepanel__feats">
            {activePersona.benefits.map((b, i) => (
              <div key={i} className="rolefeat">
                <Check size={15} />
                <span>{b}</span>
              </div>
            ))}
          </div>

          <p className="rolepanel__desc">{activePersona.fullText}</p>

          <button
            type="button"
            className="softbtn"
            onClick={() => navigate(apiKey ? '/data' : '/login')}
          >
            <Sparkles size={15} />
            <span>{apiKey ? 'Настроить данные под себя' : 'Начать бесплатно'}</span>
            <ArrowRight size={14} />
          </button>
        </div>
      )}
    </div>
  );
}
